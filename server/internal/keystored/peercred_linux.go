//go:build linux

package keystored

import (
	"errors"
	"net"

	"golang.org/x/sys/unix"
)

// peerUID returns the user ID of the process at the other end of a Unix
// socket connection, from the kernel (SO_PEERCRED), which the peer cannot
// forge.
func peerUID(c net.Conn) (uint32, error) {
	uc, ok := c.(*net.UnixConn)
	if !ok {
		return 0, errors.New("keystore: not a Unix socket connection")
	}
	raw, err := uc.SyscallConn()
	if err != nil {
		return 0, err
	}
	var cred *unix.Ucred
	var serr error
	if err := raw.Control(func(fd uintptr) {
		cred, serr = unix.GetsockoptUcred(int(fd), unix.SOL_SOCKET, unix.SO_PEERCRED)
	}); err != nil {
		return 0, err
	}
	if serr != nil {
		return 0, serr
	}
	return cred.Uid, nil
}
