namespace EasyPatch.Core.Entities;

public enum AlertRuleType
{
    /// <summary>The endpoint has not checked in for at least <see cref="AlertRule.Threshold"/> hours.</summary>
    EndpointOffline,

    /// <summary>At least one required update failed to install.</summary>
    InstallFailed,

    /// <summary>A required security update has been missing for more than <see cref="AlertRule.Threshold"/> days after it
    /// became required (after its rollout delay).</summary>
    SecurityUpdateMissing,

    /// <summary>The last successful scan is older than the policy allows.</summary>
    ScanStale,

    /// <summary>A restart has been pending for at least <see cref="AlertRule.Threshold"/> days.</summary>
    RestartPending,

    /// <summary>An organization has enrollment requests waiting for approval.</summary>
    EnrollmentPending,

    /// <summary>The operating system is unsupported, or its support ends within <see cref="AlertRule.Threshold"/> days.</summary>
    OsUnsupported,

    /// <summary>An endpoint is missing an update that fixes a CVE in the CISA Known Exploited Vulnerabilities catalog.</summary>
    KnownExploitedMissing,

    /// <summary>An update that endpoints of the organization still need is on hold (by the rollout guard or an
    /// administrator), so EasyPatch does not install it automatically.</summary>
    UpdateHeld,
}

public enum AlertSeverity
{
    Info,
    Warning,
    Critical,
}

public enum AlertStatus
{
    Open,
    Acknowledged,
    Resolved,
}

public enum NotificationChannelType
{
    Email,
    Webhook,
}

public enum WebhookFormat
{
    /// <summary>JSON document signed with HMAC-SHA256 (header X-EasyPatch-Signature).</summary>
    Generic,
    Slack,

    /// <summary>Microsoft Teams Workflows ("When a Teams webhook request is received") with an Adaptive Card.</summary>
    Teams,
}

public enum SmtpSecurity
{
    /// <summary>Plain connection upgraded with STARTTLS (required).</summary>
    StartTls,

    /// <summary>TLS from the first byte (usually port 465).</summary>
    SslOnConnect,

    /// <summary>No encryption. Only for a relay on a trusted network; credentials and messages travel in clear text.</summary>
    None,
}

public enum NotificationKind
{
    AlertsOpened,
    AlertsResolved,
    AlertsReminder,
    Test,
}

public enum DeliveryStatus
{
    Pending,
    Sent,
    Failed,
}

/// <summary>Single row (Id 1): SMTP server used by email channels, and webhook network policy. SuperAdmin only.</summary>
public sealed class NotificationSettingsRow
{
    public int Id { get; set; } = 1;
    public string? SmtpHost { get; set; }
    public int SmtpPort { get; set; } = 587;
    public SmtpSecurity SmtpSecurity { get; set; } = SmtpSecurity.StartTls;

    /// <summary>Accept any certificate from the SMTP server (e.g. an internal relay with a self-signed certificate). The
    /// connection stays encrypted, but the server's identity is not verified. Off by default; ignored with
    /// <see cref="SmtpSecurity.None"/>.</summary>
    public bool SmtpSkipCertificateValidation { get; set; }

    public string? SmtpUsername { get; set; }

    /// <summary>Encrypted with ASP.NET Data Protection; never returned by the API.</summary>
    public string? SmtpPasswordProtected { get; set; }
    public string? FromAddress { get; set; }
    public string? FromName { get; set; }

    /// <summary>Allow webhooks to private (RFC 1918 / ULA / CGNAT) addresses, e.g. an on-premises PSA. Loopback, link-local
    /// and the server's own networks are always refused.</summary>
    public bool AllowPrivateNetworkWebhooks { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
}

public sealed class NotificationChannel
{
    public const int MaxRecipients = 20;

    public Guid Id { get; set; }
    public required string Name { get; set; }
    public NotificationChannelType Type { get; set; }
    public bool Enabled { get; set; } = true;
    public List<string> EmailRecipients { get; set; } = [];
    public WebhookFormat? WebhookFormat { get; set; }

    /// <summary>Encrypted: Slack and Teams webhook URLs contain a secret.</summary>
    public string? WebhookUrlProtected { get; set; }

    /// <summary>Host name of the webhook, for display.</summary>
    public string? WebhookHost { get; set; }

    /// <summary>Generic webhooks: HMAC key (encrypted), generated by the server and shown once.</summary>
    public string? SigningSecretProtected { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
}

public sealed class AlertRule
{
    public Guid Id { get; set; }
    public required string Name { get; set; }
    public AlertRuleType Type { get; set; }
    public bool Enabled { get; set; } = true;
    public AlertSeverity Severity { get; set; } = AlertSeverity.Warning;

    /// <summary>Hours or days depending on <see cref="Type"/>; null for rules without a threshold.</summary>
    public int? Threshold { get; set; }

    /// <summary>Only endpoints of this organization (null: all).</summary>
    public Guid? OrganizationId { get; set; }

    /// <summary>Only endpoints with this tag (null: all).</summary>
    public Guid? TagId { get; set; }
    public List<Guid> ChannelIds { get; set; } = [];
    public bool NotifyOnResolve { get; set; }

    /// <summary>Remind about alerts still open (not acknowledged) after this many hours; 0 = never.</summary>
    public int RenotifyHours { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
}

public sealed class Alert
{
    public Guid Id { get; set; }
    public Guid? RuleId { get; set; }
    public AlertRuleType RuleType { get; set; }
    public Guid OrganizationId { get; set; }
    public Guid? EndpointId { get; set; }

    /// <summary>Identifies what the alert is about (rule + endpoint or organization). At most one unresolved alert per key.</summary>
    public required string DedupeKey { get; set; }
    public AlertStatus Status { get; set; }
    public AlertSeverity Severity { get; set; }
    public required string Title { get; set; }
    public string? Details { get; set; }
    public DateTimeOffset OpenedAt { get; set; }
    public DateTimeOffset LastSeenAt { get; set; }
    public DateTimeOffset? ResolvedAt { get; set; }
    public DateTimeOffset? AcknowledgedAt { get; set; }
    public string? AcknowledgedBy { get; set; }
    public DateTimeOffset? LastNotifiedAt { get; set; }

    /// <summary>Consecutive evaluations in which the condition was not met; the alert resolves at 2 (avoids flapping).</summary>
    public int ClearCount { get; set; }
}

/// <summary>Outbox of notifications. The worker sends pending rows with retries; content holds no secrets.</summary>
public sealed class NotificationDelivery
{
    public Guid Id { get; set; }
    public Guid ChannelId { get; set; }
    public NotificationKind Kind { get; set; }
    public List<Guid> AlertIds { get; set; } = [];
    public required string Subject { get; set; }

    /// <summary>JSON of the rendered message model (titles, links); rendered per channel format when sent.</summary>
    public required string Payload { get; set; }
    public DeliveryStatus Status { get; set; }
    public int Attempts { get; set; }
    public DateTimeOffset NextAttemptAt { get; set; }
    public string? LastError { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? SentAt { get; set; }
}
